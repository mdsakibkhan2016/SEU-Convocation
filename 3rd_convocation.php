<script>
    const messagesData = <?php echo json_encode($messages); ?>;

    function openMessage(index) {
        const modal = document.getElementById('messageModal');
        const data = messagesData[index];

        // Helper function to safely set or hide elements
        function setOrHide(id, value, isImage = false) {
            const el = document.getElementById(id);
            if (!el) return;

            if (value && value.trim() !== "") {
                if (isImage) {
                    el.src = value;
                    el.style.display = "block";
                } else {
                    el.innerText = value;
                    el.style.display = "block";
                }
            } else {
                el.style.display = "none";
            }
        }

        // Apply to each modal field
        setOrHide('modalImg', data.img, true);
        setOrHide('modalLogo', data.logo, true);
        setOrHide('modalName', data.name);
        setOrHide('modalTitle', data.title);
        setOrHide('modalDept', data.dept);
        setOrHide('modalOrg', data.org);
        setOrHide('modalMsg', data.msg);

        // Justify text for message content
        const modalMsg = document.getElementById('modalMsg');
        modalMsg.style.textAlign = 'justify';

        // Activate modal
        modal.classList.add('active');
        document.body.style.overflow = 'hidden';
    }

    function closeMessage() {
        const modal = document.getElementById('messageModal');
        modal.classList.remove('active');
        document.body.style.overflow = '';
    }

    // Close modal when clicking outside
    const messageModal = document.getElementById('messageModal');
    messageModal.addEventListener('click', function(event) {
        if (event.target === messageModal) {
            closeMessage();
        }
    });
</script>

