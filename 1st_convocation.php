    <script>
        const messagesData = <?php echo json_encode($messages); ?>;

        function openMessage(index) {
            const modal = document.getElementById('messageModal');
            const data = messagesData[index];

            document.getElementById('modalImg').src = data.img;
            document.getElementById('modalLogo').src = data.logo;
            document.getElementById('modalName').innerText = data.name;
            document.getElementById('modalTitle').innerText = data.title;
            document.getElementById('modalDept').innerText = data.dept;
            document.getElementById('modalOrg').innerText = data.org;
            document.getElementById('modalMsg').innerText = data.msg;

            const modalMsg = document.getElementById('modalMsg');
            modalMsg.innerText = data.msg;
            modalMsg.style.textAlign = 'justify';

            modal.classList.add('active');
            document.body.style.overflow = 'hidden';
        }

        function closeMessage() {
            const modal = document.getElementById('messageModal');
            modal.classList.remove('active');
            document.body.style.overflow = '';
        }

        // New code to close modal on outside click
        const messageModal = document.getElementById('messageModal');
        messageModal.addEventListener('click', function(event) {
            if (event.target === messageModal) {
                closeMessage();
            }
        });
    </script>

